// =============================================================
// A. ОСНОВНЫЕ ПРИНЦИПЫ И ФИЛОСОФИЯ ДП
// =============================================================
// Структура md: A. Фундаментальные принципы
//               → B. Подходы к реализации
//
// DPBasics — базовый класс всей ветки dynamic. Собственной арифметики
// не имеет: на уровне принципов достаточно базовых типов; модулярная
// арифметика и структуры подключатся в следующих разделах. Вводит
// мемоизацию (Top-Down) и табуляцию (Bottom-Up) на примерах-разминке
// (факториал, Фибоначчи, Каталана), порядок вычислений и
// восстановление ответа.
//
// Разминка (A.5) — математика рекуррентностей: её реализации —
// примеры подходов B.1 (мемоизация) и B.2 (табуляция). Полные
// модулярные версии факториала и биномов — combinatorics (a/a.md);
// числа Каталана через C(2n,n)/(n+1) — там же (C_iter).
//
// Ограничения int64 (демонстрационные версии): 20! ≈ 2.4·10¹⁸ (n ≤ 20),
// F(90) ≈ 2.9·10¹⁸ (n ≤ 90), C_30 ≈ 3.8·10¹⁷ (n ≤ 30). Модулярные
// версии появятся с задачами в следующих разделах.

struct DPBasics {

    // --- B.1. Мемоизация (Top-Down): рекурсия + запоминание ---
    // Пример — числа Фибоначчи (A.5.2): F(n) = F(n−1) + F(n−2).
    // memo[k] = -1 — «не посчитано»; каждое состояние считается один раз.
    // O(n) состояний · O(1) переходов = O(n) времени, O(n) памяти + стек.
    long long fib_memo(int n) {
        vector<long long> memo(n + 1, -1);
        function<long long(int)> rec = [&](int k) {
            if (k <= 1) return (long long)k;
            if (memo[k] != -1) return memo[k];
            return memo[k] = rec(k - 1) + rec(k - 2);
        };
        return rec(n);
    }

    // --- B.2. Табуляция (Bottom-Up): порядок зависимостей ---
    // Пример 1 — факториал (A.5.1): f(n) = n·f(n−1), f(0) = 1.
    // Порядок f(0) → f(1) → ... → f(n); каждый шаг — одно умножение.
    // O(n) времени, O(1) памяти (накопление в одном значении).
    long long fact_dp(int n) {
        long long f = 1;
        for (int i = 1; i <= n; i++) f *= i;
        return f;
    }

    // --- B.2. Табуляция: пример 2 — Fast Fibonacci (A.5.2) ---
    // F(0) → F(1) → ... → F(n): каждый член зависит от двух предыдущих,
    // храним два последних значения. O(n) времени, O(1) памяти.
    // Матричная версия O(log n) — раздел C.
    long long fib_dp(int n) {
        if (n <= 1) return n;
        long long a = 0, b = 1;              // F(0), F(1)
        for (int i = 2; i <= n; i++) {
            long long c = a + b;
            a = b;
            b = c;
        }
        return b;
    }

    // --- B.2. Табуляция: пример 3 — числа Каталана (A.5.3) ---
    // C₀ = 1, Cₙ = Σ_{i=0}^{n−1} Cᵢ·Cₙ₋₁₋ᵢ — свёртка предыдущих членов;
    // перекрёстные зависимости: C₂ нужен в C₃, C₄, ... — контроль порядка
    // циклов: внешний по возрастанию n, внутренний — по i.
    // O(n²) времени, O(n) памяти.
    long long catalan_dp(int n) {
        vector<long long> cat(n + 1, 0);
        cat[0] = 1;
        for (int i = 1; i <= n; i++)
            for (int j = 0; j < i; j++)
                cat[i] += cat[j] * cat[i - 1 - j];
        return cat[n];
    }

    // --- B.4. Восстановление ответа: минимальное число шагов до 1 ---
    // f(n) = 1 + min( min_{d ∈ dec, d ≤ n} f(n−d),
    //                 min_{p ∈ div, p | n} f(n/p) ),  f(1) = 0.
    // dec — множество допустимых вычитаний, div — множество делителей;
    // prev[n] — выбранный переход; обратный проход от n до 1 собирает
    // сам путь. O(n·(|dec| + |div|)) времени, O(n) памяти.
    // (Обобщение с произвольными операциями и ценами cᵢ — раздел B.)
    pair<int, vector<int>> min_steps_to_one_path(int n, const vector<int>& dec, const vector<int>& div) {
        vector<int> dp(n + 1, INT_MAX);
        vector<int> prev(n + 1, -1);
        dp[1] = 0;
        for (int i = 2; i <= n; i++) {
            for (int d : dec)
                if (d <= i && dp[i - d] + 1 < dp[i]) { dp[i] = dp[i - d] + 1; prev[i] = i - d; }
            for (int p : div)
                if (i % p == 0 && dp[i / p] + 1 < dp[i]) { dp[i] = dp[i / p] + 1; prev[i] = i / p; }
        }
        vector<int> path;
        for (int x = n; x != -1; x = prev[x]) path.push_back(x);
        return {dp[n], path};
    }
};

// =============================================================
// Демонстрация (сверка с ожидаемыми значениями)
// =============================================================
#ifndef DP_BASICS_MAIN
signed main() {
    DPBasics dp;
    cout << "fib_memo(45) = " << dp.fib_memo(45) << " (ожидаем 1134903170)\n";
    cout << "fact_dp(20) = " << dp.fact_dp(20) << " (ожидаем 2432902008176640000)\n";
    cout << "fib_dp(90) = " << dp.fib_dp(90) << " (ожидаем 2880067194370816120)\n";
    cout << "catalan_dp(30) = " << dp.catalan_dp(30) << " (ожидаем 3814986502092304)\n";
    auto res = dp.min_steps_to_one_path(10, {1}, {2, 3});
    cout << "min_steps_to_one(10, dec={1}, div={2,3}) = " << res.first << " (ожидаем 3): путь";
    for (int x : res.second) cout << " " << x;
    cout << "\n";
}
#endif // DP_BASICS_MAIN
#endif // DYNAMIC_A_CPP
